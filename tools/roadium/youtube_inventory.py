#!/usr/bin/env python3
"""Freeze explicit YouTube rule references; native results supply compatibility.

Generic rules may also affect YouTube. This conservative literal inventory
includes exclusions and incidental references, rather than pretending all
matches target a YouTube document. No URL is fetched by this tool.
"""
from pathlib import Path
import argparse
import gzip
import hashlib
import json

FORK = Path(__file__).resolve().parents[2]
TOKENS = ('youtube', 'youtu.be', 'googlevideo', 'ytimg', 'youtubekids')


def digest(data):
    return hashlib.sha256(data).hexdigest()


def collect(fork=FORK):
    manifest = json.loads((fork / 'build/roadium/filters/manifest.json').read_text(encoding='utf-8'))
    sources, rows = [], []
    for item in manifest['inputs']:
        packed = (fork / 'build/roadium/filters' / item['file']).read_bytes()
        assert digest(packed) == item['gzip_sha256'], item['file']
        data = gzip.decompress(packed)
        assert digest(data) == item['sha256'], item['file']
        sources.append(dict(name=item['file'].removesuffix('.gz'), url=item['canonical_url'],
                            version=item['version'], revision=manifest['revision'],
                            sha256=digest(data), data=data))
    path = fork / 'tools/filters/experimental-cromite-filters.txt'
    data = path.read_bytes()
    sources.append(dict(name=path.name,
                        url='https://raw.githubusercontent.com/uazo/cromite/master/tools/filters/' + path.name,
                        version='', revision='11507ac1061b5ea227806f5e84db5a57df6ccf6a',
                        sha256=digest(data), data=data))
    # Audit-only snapshots of other first-run selections; never browser resources.
    extra_root = fork / 'tools/roadium/youtube-snapshots'
    extra_manifest = json.loads((extra_root / 'manifest.json').read_text(encoding='utf-8'))
    for item in extra_manifest['inputs']:
        packed = (extra_root / item['file']).read_bytes()
        assert digest(packed) == item['gzip_sha256'], item['file']
        data = gzip.decompress(packed)
        assert digest(data) == item['sha256'], item['file']
        sources.append(dict(name=item['file'].removesuffix('.gz'), url=item['canonical_url'],
                            version=item['version'], revision=extra_manifest['revision'],
                            sha256=digest(data), data=data))
    for source in sources:
        for number, rule in enumerate(source.pop('data').decode('utf-8').splitlines(), 1):
            if not rule.strip() or rule.startswith(('!', '[')):
                continue
            if not any(token in rule.lower() for token in TOKENS):
                continue
            kind = 'scriptlet' if '#$#' in rule else 'cosmetic' if '#' in rule else 'network'
            rows.append(dict(id=f"{source['name']}:{number}", source=source['name'],
                             line=number, url=source['url'], rule=rule,
                             sha256=digest(rule.encode('utf-8')), kind=kind))
    return dict(format=1, scope='Literal references including exclusions; generic rules are outside this inventory',
                inputs=sources, rules=rows)


def generate_header(inventory):
    lines = ['// Copyright 2026 Roadium Browser contributors.',
             '// SPDX-License-Identifier: GPL-3.0-only',
             '// Generated by tools/roadium/youtube_inventory.py; do not edit.',
             '// Rule text retains the licenses/attribution in the frozen input manifest.',
             'struct YoutubeAuditRule { const char* id; const char* url; const char* rule; };',
             'constexpr YoutubeAuditRule kYoutubeAuditRules[] = {']
    for row in inventory['rules']:
        # ASCII JSON string escaping is valid for these C++ string literals.
        lines.append('  {' + ', '.join(json.dumps(row[k], ensure_ascii=True) for k in ('id', 'url', 'rule')) + '},')
    return '\n'.join(lines + ['};', ''])


def attach_native_results(inventory, native):
    """Require a complete successful run, matching every source/line identifier."""
    actual = {}
    for iteration in native['per_iteration_data']:
        for attempts in iteration.values():
            for attempt in attempts:
                if attempt['status'] != 'SUCCESS':
                    raise ValueError('Native run contains a failed test')
                for line in attempt.get('output_snippet', '').splitlines():
                    if not line.startswith('ROADIUM_YOUTUBE_AUDIT '):
                        continue
                    value = json.loads(line.removeprefix('ROADIUM_YOUTUBE_AUDIT '))
                    if value['id'] in actual:
                        raise ValueError('Duplicate audit result: ' + value['id'])
                    actual[value['id']] = value
    if set(actual) != {row['id'] for row in inventory['rules']}:
        raise ValueError('Native audit does not cover this frozen inventory exactly')
    for row in inventory['rules']:
        result = actual[row['id']]
        if result.get('rule') != row['rule'] or result.get('url') != row['url']:
            raise ValueError('Native audit source identity/text mismatch: ' + row['id'])
        counters = result['converter_privileged' if result['source_privileged_allowed']
                          else 'converter_unprivileged']
        if sum(counters.values()) != 1 or not result['live_advanced_off_empty']:
            raise ValueError('Invalid rule outcome: ' + row['id'])
        row['native'] = result
        row['parser_policy_result'] = next(key for key, value in counters.items() if value)
        row['runtime_evidence'] = 'Generated calls and policy verified natively; actual JS effects require installed fixture/live evidence'
        row['decision'] = ('Retain upstream unchanged; accepted syntax is not a promise of runtime effect'
                           if counters['accepted'] else
                           'Retain safe rejection; no stripping, replacement or command support added')
    return inventory


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--inventory', type=Path, required=True)
    parser.add_argument('--header', type=Path)
    parser.add_argument('--native-results', type=Path)
    args = parser.parse_args()
    data = collect()
    if args.native_results:
        data = attach_native_results(data, json.loads(args.native_results.read_text(encoding='utf-8')))
    args.inventory.parent.mkdir(parents=True, exist_ok=True)
    args.inventory.write_text(json.dumps(data, indent=2) + '\n', encoding='utf-8', newline='\n')
    if args.header:
        args.header.write_text(generate_header(data), encoding='utf-8', newline='\n')
    print(f"Inventoried {len(data['rules'])} explicit references; compatibility requires native results")


if __name__ == '__main__':
    main()
